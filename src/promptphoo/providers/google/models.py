def get_vertex_model_default_region(model_name: str) -> str | None:
    if model_name in VERTEX_GLOBAL_DEFAULT_MODELS:
        return "global"
    if model_name in VERTEX_US_EAST5_DEFAULT_MODELS:
        return "us-east5"
    return None


def get_vertex_api_host_for_region(region: str) -> str:
    if region == "global":
        return "aiplatform.googleapis.com"
    if region in ("us", "eu"):
        return f"aiplatform.{region}.rep.googleapis.com"
    return f"{region}-aiplatform.googleapis.com"


