"""Copy the raw dedent template segments of upstream's synthesis prompts into promptphoo.

    python tools/gen_synthesis_templates.py [/path/to/promptfoo]

Writes src/promptphoo/synthesis/templates.py from src/testCase/synthesis.ts and
src/assertions/synthesis.ts. Each dedent`...` literal becomes a tuple of its raw segments
(escapes unprocessed, as `strings.raw`), in source order; `synthesis.dedent` then
interpolates them exactly as the npm tag does.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "promptphoo" / "synthesis" / "templates.py"
SOURCES = {
    "src/testCase/synthesis.ts": [
        "PERSONAS_PROMPTS", "PERSONAS", "TC_PROMPTS", "TC_PROMPT", "TC_EXISTING", "TC_TEST",
        "TC_MAIN",
    ],
    "src/assertions/synthesis.ts": ["NEW_QUESTIONS", "PYTHON_PROMPT"],
}  # fmt: skip
HEADER = '''"""Raw dedent template segments of upstream's synthesis prompts.

Generated by tools/gen_synthesis_templates.py from src/testCase/synthesis.ts and
src/assertions/synthesis.ts; do not edit. Trailing whitespace is part of the prompts.
"""
# ruff: noqa: E501, W291, W293

'''


def _skip_string(src: str, j: int) -> int:
    quote = src[j]
    j += 1
    while src[j] != quote:
        j += 2 if src[j] == "\\" else 1
    return j + 1


def parse_template(src: str, i: int) -> tuple[list[str], int]:
    """Raw segments of the template literal starting at src[i] == '`', and the end index."""
    assert src[i] == "`"
    i += 1
    segments: list[str] = []
    cur: list[str] = []
    while True:
        c = src[i]
        if c == "\\":
            cur.append(src[i : i + 2])
            i += 2
        elif c == "`":
            segments.append("".join(cur))
            return segments, i + 1
        elif c == "$" and src[i + 1] == "{":
            segments.append("".join(cur))
            cur = []
            j, depth = i + 2, 1
            while depth:
                ch = src[j]
                if ch == "`":
                    j = parse_template(src, j)[1]
                    continue
                if ch in "'\"":
                    j = _skip_string(src, j)
                    continue
                depth += {"{": 1, "}": -1}.get(ch, 0)
                j += 1
            i = j
        else:
            cur.append(c)
            i += 1


def dedent_templates(src: str) -> list[tuple[int, list[str]]]:
    found = []
    for m in re.finditer(r"dedent`", src):
        segments, _ = parse_template(src, m.end() - 1)
        found.append((src.count("\n", 0, m.start()) + 1, segments))
    return found


def _literal(segment: str) -> str:
    if '"""' in segment or segment.endswith(("\\", '"')):
        return repr(segment)
    return 'r"""' + segment + '"""'


def render_block(upstream_file: str, src: str, names: list[str]) -> str:
    templates = dedent_templates(src)
    if len(templates) != len(names):
        raise SystemExit(f"{upstream_file}: expected {len(names)} dedent templates")
    out = []
    for (line, segments), name in zip(templates, names, strict=True):
        out.append(f"\n# {upstream_file}:{line}\n{name} = (\n")
        out.extend(f"    {_literal(s)},\n" for s in segments)
        out.append(")\n")
    return "".join(out)


def main() -> None:
    upstream = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "promptfoo")
    blocks = [
        render_block(upstream_file, (upstream / upstream_file).read_text(), names)
        for upstream_file, names in SOURCES.items()
    ]
    OUT.write_text(HEADER + "".join(blocks))


if __name__ == "__main__":
    main()
