#!/usr/bin/env node
// Regenerates src/promptphoo/providers/azure/tables.py from upstream promptfoo's Azure pricing
// tables (src/providers/azure/{defaults,util}.ts). Node evaluates the values, so float arithmetic
// such as `1.25 / 1000000` is bit-for-bit upstream's.
//
// Usage: node tools/gen_azure_tables.mjs [../promptfoo]   (Node >= 22.6 for --experimental-strip-types)
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const upstream = resolve(process.argv[2] ?? join(here, '..', '..', 'promptfoo'));
const src = (name) => readFileSync(join(upstream, 'src/providers/azure', name), 'utf8');
const stripImports = (text) => text.replace(/^import[\s\S]*?;\n/gm, '');

const utilNames = [
  'AZURE_CACHE_READ_RATES',
  'AZURE_LONG_CONTEXT_CACHE_READ_RATES',
  'AZURE_PRIORITY_MULTIPLIERS',
  'AZURE_SHORT_CONTEXT_PRIORITY_MULTIPLIERS',
];
const dir = mkdtempSync(join(tmpdir(), 'azure-tables-'));
writeFileSync(join(dir, 'defaults.ts'), stripImports(src('defaults.ts')));
writeFileSync(
  join(dir, 'util.ts'),
  `import { AZURE_MODELS } from './defaults.ts';
const dedent: any = (s: any) => s;
const clampCachedTokens: any = () => 0;
${stripImports(src('util.ts'))}
export { ${utilNames.join(', ')} };
`,
);
writeFileSync(
  join(dir, 'dump.ts'),
  `import * as defaults from './defaults.ts';
import * as util from './util.ts';
const plain = (v: unknown): unknown => (v instanceof Map ? Object.fromEntries(v) : v);
const out: Record<string, unknown> = {
  DEFAULT_AZURE_API_VERSION: defaults.DEFAULT_AZURE_API_VERSION,
  AZURE_MODELS: defaults.AZURE_MODELS,
};
for (const name of ${JSON.stringify(utilNames)}) out[name] = plain((util as any)[name]);
process.stdout.write(JSON.stringify(out));
`,
);
const tables = JSON.parse(
  execFileSync(
    process.execPath,
    ['--experimental-strip-types', '--no-warnings', join(dir, 'dump.ts')],
    { encoding: 'utf8' },
  ),
);

const num = (value) => {
  const s = String(value);
  return Number.isInteger(value) ? s : /e/.test(s) && !/\./.test(s) ? s.replace('e', '.0e') : s;
};
const py = (value) => {
  if (value === null || value === undefined) return 'None';
  if (value === true) return 'True';
  if (value === false) return 'False';
  if (typeof value === 'number') return num(value);
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(py).join(', ')}]`;
  return `{${Object.entries(value)
    .map(([k, v]) => `${JSON.stringify(k)}: ${py(v)}`)
    .join(', ')}}`;
};
const lines = [];
for (const [name, value] of Object.entries(tables)) {
  if (Array.isArray(value)) {
    lines.push(`${name}: Any = [\n${value.map((v) => `    ${py(v)},`).join('\n')}\n]`);
  } else if (value && typeof value === 'object') {
    const entries = Object.entries(value).map(([k, v]) => `    ${JSON.stringify(k)}: ${py(v)},`);
    lines.push(`${name}: Any = {\n${entries.join('\n')}\n}`);
  } else {
    lines.push(`${name}: Any = ${py(value)}`);
  }
}
const header = `"""Azure model pricing tables. Generated by tools/gen_azure_tables.mjs from upstream
src/providers/azure/{defaults,util}.ts (v0.125.1). Do not edit by hand; regenerate.
"""

# ruff: noqa: E501
# fmt: off
from typing import Any

`;
const target = join(here, '..', 'src/promptphoo/providers/azure/tables.py');
writeFileSync(target, `${header}${lines.join('\n\n')}\n`);
console.log(`wrote ${target}`);
